"""Write android/app/requirements-android.txt from uv.lock: the runtime dependency
closure at its pinned versions, minus packages the phone gets from Chaquopy's own index
(numpy, scipy, pandas, lxml, pyyaml, zstandard) which must stay unpinned so the index
resolves them, and minus everything only the pc extra needs.

Unpinned means the phone may resolve an older release than the lock pins (seen:
pandas 2.1.3 against a 2.2 floor, zstandard 0.23.0 against 0.25.0). Those are
compression, framing and dataframe packages, never the clinical arithmetic, and the
on-phone runs in Task 25 are the check that phone and PC agree where it matters."""

import tomllib
from pathlib import Path

FROM_CHAQUOPY_INDEX = {"numpy", "scipy", "pandas", "lxml", "pyyaml", "tokenizers", "zstandard"}

# Declared by langgraph-checkpoint-sqlite but never imported (checked on the PC; see
# android/wheels/BUILD.md). PyPI ships no source distribution for it, so the phone
# installs the checkpointer with --no-deps (see android/app/build.gradle.kts) and this
# package must not appear in the requirements file at all.
EXCLUDED_FROM_PHONE = {"sqlite-vec"}


def generate(lock_path: Path, pyproject_path: Path) -> list[str]:
    lock = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    pyproject = tomllib.loads(pyproject_path.read_text(encoding="utf-8"))
    by_name = {p["name"]: p for p in lock["package"]}
    roots = [d.split(">")[0].split("<")[0].split("=")[0].strip() for d in pyproject["project"]["dependencies"]]
    closure: set[str] = set()
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in closure or name not in by_name:
            continue
        closure.add(name)
        for dep in by_name[name].get("dependencies", []):
            stack.append(dep["name"])
    lines = []
    for name in sorted(closure):
        if name == "wha":
            continue
        if name in EXCLUDED_FROM_PHONE:
            continue
        if name in FROM_CHAQUOPY_INDEX:
            lines.append(name)
        else:
            lines.append(f"{name}=={by_name[name]['version']}")
    return lines


def main() -> None:
    lines = generate(Path("uv.lock"), Path("pyproject.toml"))
    out = Path("android/app/requirements-android.txt")
    out.write_text("# Generated by tools/android_requirements.py from uv.lock. Do not edit.\n" + "\n".join(lines) + "\n", encoding="utf-8")
    print(out, len(lines), "packages")


if __name__ == "__main__":
    main()
