"""Generates the phone's graph frame from the canonical step list.

Reads CANONICAL_PIPELINE_STEPS from src/wha/models.py and writes
android/app/src/main/java/dev/wha/app/core/CanonicalSteps.kt. Group membership
follows the five-group table in spec section 7.1 of
docs/superpowers/specs/2026-09-10-android-app-design.md (by ordinal range, with
the step ids asserted so a reorder on the PC side fails loudly here rather than
drawing a wrong frame).

Run after any change to the step list:
    uv run python tools/android_canonical_steps.py
tests/unit/android/test_canonical_steps.py asserts the committed file equals
what this script produces now, so the frame cannot drift from the step list.
"""

from pathlib import Path

from wha.models import CANONICAL_PIPELINE_STEPS

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "android/app/src/main/java/dev/wha/app/core/CanonicalSteps.kt"

# Spec section 7.1, in ordinal order. Each entry lists the step ids in that group.
GROUPS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Reading the watch", ("collect", "store", "sleep_window", "features")),
    ("Comparing with your normal", ("baseline", "subtract_explained", "detect")),
    ("What you have told us", ("safety_floor",)),
    (
        "The investigation",
        (
            "episode_open",
            "preload",
            "investigate",
            "believe",
            "decide",
            "ask",
            "answer",
            "conclude",
            "critique",
            "review",
            "deliver",
        ),
    ),
    ("The safety rules on your words", ("safety_phrase_rules", "safety_triage")),
)

HEADER = """package dev.wha.app.core

// Generated by tools/android_canonical_steps.py from CANONICAL_PIPELINE_STEPS in
// src/wha/models.py. Do not edit by hand: change the step list or the group table
// in the generator and re-run it.
"""


def main() -> None:
    ordered = sorted(CANONICAL_PIPELINE_STEPS, key=lambda s: s.ordinal)
    flat = [step_id for _, ids in GROUPS for step_id in ids]
    assert [s.step_id for s in ordered] == flat, (
        "the PC step list no longer matches the group table in this script; "
        "update GROUPS before regenerating"
    )
    lines = [HEADER]
    lines.append(
        "data class CanonicalStep(val id: String, val ordinal: Int, val layer: String, val group: String)"
    )
    lines.append("")
    lines.append("object CanonicalSteps {")
    lines.append("    val all: List<CanonicalStep> = listOf(")
    by_id = {s.step_id: s for s in ordered}
    for group, ids in GROUPS:
        for step_id in ids:
            step = by_id[step_id]
            lines.append(
                f'        CanonicalStep(id = "{step.step_id}", ordinal = {step.ordinal}, '
                f'layer = "{step.layer.value}", group = "{group}"),'
            )
    lines.append("    )")
    lines.append("}")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TARGET} ({len(ordered)} steps)")


if __name__ == "__main__":
    main()
