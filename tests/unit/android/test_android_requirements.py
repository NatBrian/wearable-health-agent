"""The generated Android requirements must match the lock, or the phone installs
versions the PC never tested. Regenerating without writing and comparing fails the
build the moment uv.lock changes without a regeneration."""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def test_android_requirements_match_the_lock() -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    try:
        import android_requirements
    finally:
        sys.path.remove(str(ROOT / "tools"))
    lines = android_requirements.generate(ROOT / "uv.lock", ROOT / "pyproject.toml")
    expected = (
        "# Generated by tools/android_requirements.py from uv.lock. Do not edit.\n"
        + "\n".join(lines)
        + "\n"
    )
    committed = (ROOT / "android/app/requirements-android.txt").read_text(encoding="utf-8")
    assert committed == expected, "run: uv run python tools/android_requirements.py"
