"""
`archive/` and `research/` are deliberately excluded. They record what was believed when
they were written, and editing a frozen record is its own kind of rewriting.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

KNOWLEDGE = Path("data/knowledge")

# Only these three values mean anything. CITED carries a source, DERIVED carries working,
# ASSUMED means no published value exists, which is a real answer and not a missing one.
VALID_PROVENANCE = {"CITED", "DERIVED", "ASSUMED"}

AUTHORSHIP_CLAIM = re.compile(
    r"authored by a human|written by a human|human[- ]authored|human[- ]written",
    re.IGNORECASE,
)

SEARCH_ROOTS = (Path("src"), Path("data/knowledge"), Path(".agents"), Path("tools"))
SEARCH_FILES = (
    Path("README.md"),
    Path("AGENTS.md"),
    Path("CLAUDE.md"),
    Path("GEMINI.md"),
    Path("docs/CORPUS-VERIFICATION.md"),
    Path("docs/RESEARCH-AGENTIC-TRIAGE.md"),
    Path("docs/DISCLOSURES.md"),
)


def _candidate_files() -> list[Path]:
    found: list[Path] = []
    for root in SEARCH_ROOTS:
        if not root.exists():
            continue
        for path in root.rglob("*"):
            if path.is_file() and path.suffix in {".py", ".md", ".yaml", ".yml", ".json"}:
                found.append(path)
    found.extend(p for p in SEARCH_FILES if p.exists())
    return found


def test_nothing_claims_a_person_wrote_the_clinical_content() -> None:
    """The claim is false. It must not return anywhere the code or a reader can see it."""
    offenders: list[str] = []
    for path in _candidate_files():
        text = path.read_text(encoding="utf-8", errors="replace")
        for number, line in enumerate(text.splitlines(), start=1):
            if AUTHORSHIP_CLAIM.search(line):
                offenders.append(f"{path.as_posix()}:{number}: {line.strip()}")
    assert not offenders, (
        "data/knowledge/ was generated by a language model. These lines say otherwise:\n"
        + "\n".join(offenders)
    )


def test_no_file_claims_a_sensitivity_sweep_that_does_not_exist() -> None:
    """Fourteen figures were annotated "Swept". The only sweep is over the interruption cost.

    `COST_WEIGHT_SWEEP` in `wha/eval/policy_oracle.py` ranges over
    `POLICY_COST_PER_INTERRUPT` and nothing else. No effect size and no likelihood row in
    these tables has ever been varied by any code here. If a real sweep is built, this test
    should be changed to assert it covers the figures that claim it.
    """
    offenders: list[str] = []
    for name in ("causes.yaml", "probes.yaml"):
        text = (KNOWLEDGE / name).read_text(encoding="utf-8")
        for number, line in enumerate(text.splitlines(), start=1):
            if re.search(r"\bswept\b", line, re.IGNORECASE):
                offenders.append(f"{name}:{number}: {line.strip()}")
    assert not offenders, "These claim a sweep that no code performs:\n" + "\n".join(offenders)


def test_every_cause_carries_a_provenance_and_backs_it_up() -> None:
    """A cited number needs a citation, a derived number needs working, assumed needs neither.

    The failure this prevents is a number that looks sourced because the row beside it is.
    """
    causes = yaml.safe_load((KNOWLEDGE / "causes.yaml").read_text(encoding="utf-8"))["causes"]
    assert causes, "causes.yaml has no rows"

    for row in causes:
        cause = row["cause"]
        provenance = row.get("provenance")
        assert provenance in VALID_PROVENANCE, f"{cause}: provenance {provenance!r}"

        if provenance == "CITED":
            assert row.get("citation"), f"{cause}: CITED with no citation"
        elif provenance == "DERIVED":
            assert row.get("derivation"), f"{cause}: DERIVED with no derivation shown"
        else:
            assert row.get("assumption"), (
                f"{cause}: ASSUMED with no statement of what was assumed. "
                "ASSUMED is an answer, but it has to say what the assumption is."
            )


def test_every_probe_likelihood_carries_a_provenance() -> None:
    """The 64 answer likelihoods are unmeasurable, which is fine. Silence about it is not."""
    probes = yaml.safe_load((KNOWLEDGE / "probes.yaml").read_text(encoding="utf-8"))["probes"]
    assert probes, "probes.yaml has no rows"

    for row in probes:
        probe = row["probe_id"]
        provenance = row.get("provenance")
        assert provenance in VALID_PROVENANCE, f"{probe}: provenance {provenance!r}"
        if provenance == "ASSUMED":
            assert row.get("assumption"), f"{probe}: ASSUMED with no statement of the assumption"
        elif provenance == "CITED":
            assert row.get("citation"), f"{probe}: CITED with no citation"


def _causes() -> list[dict]:
    """Every cause row, straight from the YAML the product loads."""
    return yaml.safe_load((KNOWLEDGE / "causes.yaml").read_text(encoding="utf-8"))["causes"]


def test_no_cause_is_labelled_cited_for_a_number_its_paper_does_not_contain() -> None:
    """CITED must mean the number is IN the source, not near it.

    Three rows were CITED on 5 September 2026 and none of them should have been.

    - alcohol: the citation's own text said "it is not what the paper measured". 2.60 is
      the midpoint of a two-drink span the paper reports as a contrast, not a per-drink
      effect.
    - luteal: 3.91 bpm really is Goodale's, but the base rate is derived from "12 to 14
      luteal days per 28-day cycle" and the spread is in no paper at all.
    - recovery_tail: Radin supports the 79-day window and none of the row's three numbers.

    A row carries ONE provenance for four numbers, so the label has to describe the
    weakest of them. That is the rule the episode panel already applies when it marks a
    cause "not measured"; this asserts the YAML obeys it too.
    """
    for row in _causes():
        provenance = row.get("provenance")
        if provenance != "CITED":
            continue
        backing = str(row.get("citation") or "")
        assert "not what the paper measured" not in backing.lower(), (
            f"{row['cause']} is CITED and its own citation says the paper did not measure it"
        )
        assert "NO EVIDENCE FOUND" not in backing.upper(), (
            f"{row['cause']} is CITED and its own backing says no evidence was found"
        )


def test_a_derived_row_holding_an_unevidenced_number_is_marked_on_screen() -> None:
    """ "From a study" must not appear over a row containing a figure nobody measured.

    The screen marked a cause unsourced only when its provenance was ASSUMED or its
    temporal profile had no source. Every DERIVED row therefore read "from a study",
    including the three relabelled from CITED, each of which names at least one number as
    NO EVIDENCE FOUND inside its own derivation.
    """
    from wha.service.belief import get_knowledge_provenance

    provenance = get_knowledge_provenance()

    for row in _causes():
        backing = str(row.get("derivation") or row.get("assumption") or "")
        if "NO EVIDENCE FOUND" not in backing.upper():
            continue
        meta = provenance[str(row["cause"])]
        assert meta.get("has_unevidenced_number") == "yes", (
            f"{row['cause']} names an unevidenced number and the screen is not told"
        )

    # And the three that were mislabelled are all caught by it.
    for cause in ("alcohol", "luteal", "recovery_tail"):
        assert provenance[cause]["has_unevidenced_number"] == "yes", cause
