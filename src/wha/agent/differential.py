"""Why each candidate cause is or is not credited, derived from the evidence gathered.

``DifferentialItem`` has carried ``supporting: []`` and ``contradicting: []`` since it was
written, so every episode presented a ranked list of causes with a probability against each
and no reason attached to any of them. A number with no reason is the thing a clinical
system should never show.

Nothing here is generated by a model. Each line is read off the same tables the belief
model computes with: the answer likelihoods in ``probes.yaml``, the effect sizes in
``causes.yaml``, and the feature conditions in ``wha.belief.likelihood``. The wording
differs from that module but the conditions are deliberately the same ones, so a reason
shown to a person cannot disagree with the arithmetic that moved the belief.
"""

from collections.abc import Sequence
from typing import Any

from wha.belief.causes import load_causes
from wha.belief.likelihood import load_probes_raw
from wha.constants import MIN_NOCTURNAL_MINUTES, SHORT_SLEEP_HOURS
from wha.models import (
    Answer,
    BeliefState,
    CauseId,
    Detection,
    DifferentialItem,
    MeasurementResult,
    NightlyFeatures,
)


def _answer_reasons(
    cause: CauseId,
    answers: Sequence[Answer],
    probes: dict[str, Any],
) -> tuple[list[str], list[str]]:
    """What the person said about this cause, and which way it pointed."""
    supporting: list[str] = []
    contradicting: list[str] = []

    for answer in answers:
        probe = probes.get(answer.probe_id)
        if not probe or str(probe.get("target_cause")) != cause.value:
            continue

        if answer.declined or answer.option_id is None:
            contradicting.append(
                f"You were asked about this ({answer.probe_id}) and did not answer, so "
                "nothing was inferred either way."
            )
            continue

        likelihood = probe.get("likelihood", {}) or {}
        p_present = likelihood.get("present", {}).get(answer.option_id)
        p_absent = likelihood.get("absent", {}).get(answer.option_id)
        label = next(
            (
                str(option.get("label"))
                for option in probe.get("answer_space", []) or []
                if str(option.get("option_id")) == str(answer.option_id)
            ),
            str(answer.option_id),
        )
        if p_present is None or p_absent is None:
            continue

        line = (
            f'You answered "{label}". That answer is expected in {float(p_present):.0%} of '
            f"cases where this is contributing, against {float(p_absent):.0%} where it is "
            f"not (probes.yaml, {answer.probe_id}, provenance "
            f"{probe.get('provenance', 'unstated')})."
        )
        if float(p_present) > float(p_absent):
            supporting.append(line)
        elif float(p_present) < float(p_absent):
            contradicting.append(line)

    return supporting, contradicting


def _feature_reasons(
    cause: CauseId,
    features: Sequence[NightlyFeatures],
    measurements: Sequence[MeasurementResult],
) -> tuple[list[str], list[str]]:
    """What the watch itself says about this cause.

    The conditions mirror ``compute_exercise_logfactor``, ``compute_sleep_logfactor``,
    ``compute_coverage_logfactor`` and ``compute_measurement_logfactor`` exactly, so the
    reason shown and the factor applied always agree.
    """
    supporting: list[str] = []
    contradicting: list[str] = []

    if cause is CauseId.EXERTION and any(f.exercise_end_offset_h is not None for f in features):
        contradicting.append(
            "A workout was recorded on the watch and has already been subtracted from the "
            "night's reading, so this cause means exertion the device missed."
        )

    if cause is CauseId.SLEEP_RESTRICTION:
        slept = [f.sleep_hours for f in features if f.sleep_hours is not None]
        if slept:
            latest = slept[-1]
            if latest < SHORT_SLEEP_HOURS:
                supporting.append(
                    f"The watch recorded {latest:.1f} hours of sleep, below the "
                    f"{SHORT_SLEEP_HOURS} hour mark this system treats as short."
                )
            elif latest >= 7.0:
                contradicting.append(
                    f"The watch recorded {latest:.1f} hours of sleep, which is not short."
                )

    if cause is CauseId.SENSOR_ARTIFACT:
        bad = [
            f
            for f in features
            if f.implausible_dropped > 0 or f.coverage_minutes < MIN_NOCTURNAL_MINUTES
        ]
        if bad:
            worst = min(bad, key=lambda f: f.coverage_minutes)
            supporting.append(
                f"Data quality was poor on at least one night: {worst.coverage_minutes} "
                f"minutes of usable coverage and {worst.implausible_dropped} readings "
                "dropped as implausible."
            )
        if any(m.satisfied and m.kind == "spot_resting_hr" for m in measurements):
            contradicting.append(
                "A spot heart rate measurement you took by hand agreed with the watch, so "
                "the reading is unlikely to be a sensor problem."
            )

    return supporting, contradicting


def _size_reasons(cause_prior: Any, nights: Sequence[Detection]) -> tuple[list[str], list[str]]:
    """Whether this cause is even large enough to explain the rise that was measured."""
    residuals = [n.residual_bpm for n in nights if n.residual_bpm is not None]
    if not residuals:
        return [], []

    peak_effect = cause_prior.effect_mean_bpm * max(cause_prior.profile or [1.0])
    observed = max(residuals)
    if peak_effect <= 0:
        return [], []

    if peak_effect >= observed * 0.5:
        return (
            [
                (
                    f"Size fits: at its peak this contributes about {peak_effect:.1f} "
                    f"bpm, against the {observed:.1f} bpm rise actually measured "
                    f"({cause_prior.citation.strip().splitlines()[0]})."
                )
            ],
            [],
        )
    if peak_effect < observed * 0.25:
        return (
            [],
            [
                (
                    "Size does not fit: at its peak this contributes only about "
                    f"{peak_effect:.1f} bpm, well under the {observed:.1f} bpm rise "
                    "measured, so it cannot account for the night on its own."
                )
            ],
        )
    return [], []


def ground_differential(
    belief: BeliefState,
    nights: Sequence[Detection] = (),
    features: Sequence[NightlyFeatures] = (),
    answers: Sequence[Answer] = (),
    measurements: Sequence[MeasurementResult] = (),
    top_n: int = 5,
    cycle_applicable: bool | None = None,
) -> list[DifferentialItem]:
    """The causes this episode's evidence MOVED, most-moved first, each with its reasons.

    Ranked by movement, not by size, and that is the correction that matters.

    A ranked bar chart of final probabilities reads like a doctor's list of likely
    diagnoses. It is not one: the twelve numbers are independent, they do not add to 1, and
    they do not compete. A cause that is common and small scores high on ANY raised night,
    because something has to explain the rise. On a real closed episode the system
    concluded LIKELY_ILLNESS and the chart underneath put stress at 0.92 first, with the
    reason "Nothing gathered in this episode speaks to this cause either way".

    Once you know that a flagged night is usually noise, which the cohort measurement
    shows, the common-and-small causes rising is the expected behaviour rather than a
    finding. What this episode learned is the DIFFERENCE between where a cause started and
    where it ended, and ordering by that turns the most misleading panel in the product
    into the most informative one.
    """
    probes = load_probes_raw()
    priors = {p.cause: p for p in load_causes()}

    # Where every cause sat before this episode's evidence: the prior alone, computed by
    # the same function with nothing given to it.
    from wha.belief import update_belief

    before = update_belief(episode_nights=[], luteal_applicable=cycle_applicable).marginals

    # EVERY cause is a candidate, and the top_n cut happens AFTER ranking by movement.
    #
    # This iterated `belief.top(top_n)`, the five largest, and then sorted those five by
    # movement. A cause the evidence moved hard but left small was therefore never a
    # candidate at all, which is exactly the cause this panel exists to surface: on a
    # raised night the common-and-small causes are always large, so "large" is the one
    # criterion guaranteed not to be informative. Reproduced before the change: the true
    # top five by movement included sensor_artifact, and the panel showed stress instead.
    items: list[tuple[float, DifferentialItem]] = []
    for cause, probability in belief.marginals.items():
        supporting: list[str] = []
        contradicting: list[str] = []

        a_sup, a_con = _answer_reasons(cause, answers, probes)
        f_sup, f_con = _feature_reasons(cause, features, measurements)
        supporting += a_sup + f_sup
        contradicting += a_con + f_con

        prior = priors.get(cause)
        if prior is not None:
            s_sup, s_con = _size_reasons(prior, nights)
            supporting += s_sup
            contradicting += s_con

        if cause is CauseId.LUTEAL and cycle_applicable is None:
            contradicting.append(
                "Whether the menstrual cycle applies to you has not been established, so "
                "this is not being counted as an explanation. It is the largest benign "
                "effect in the table, and assuming it applies would explain away exactly "
                "the elevations this system exists to investigate."
            )

        if not supporting and not contradicting:
            contradicting.append(
                "Nothing gathered in this episode speaks to this cause either way. Its "
                f"position reflects its base rate of {prior.base_rate:.1%} of nights alone."
                if prior is not None
                else "Nothing gathered in this episode speaks to this cause either way."
            )

        started = float(before.get(cause, 0.0))
        moved = probability - started
        # The movement, stated first, because it is the thing this panel is ordered by and
        # a reader should not have to infer it from two numbers in different places.
        movement = (
            f"This episode moved it from {started:.1%} to {probability:.1%}, "
            f"{'up' if moved >= 0 else 'down'} {abs(moved):.1%}."
            if abs(moved) >= 0.005
            else (
                f"This episode did not move it. It sits at {probability:.1%}, which is "
                "where its base rate alone puts it."
            )
        )
        items.append(
            (
                abs(moved),
                DifferentialItem(
                    cause=cause,
                    probability=round(probability, 4),
                    moved=round(moved, 4),
                    supporting=[movement, *supporting],
                    contradicting=contradicting,
                ),
            )
        )

    # Most-moved first. The list order IS the ranking the interface draws, so this is where
    # the correction lives; DifferentialItem is frozen by the contract and carries no rank.
    items.sort(key=lambda pair: (-pair[0], -pair[1].probability, pair[1].cause.value))
    return [item for _, item in items[:top_n]]
