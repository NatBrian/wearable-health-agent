"""Something to hand a clinician, so "call 995" is not the last useful thing said.

Telling someone to seek care and then stopping is not help. They arrive with nothing, and
the reason they came is a sentence they half remember from an app.

**Structure: SBAR.** Situation, Background, Assessment, Recommendation is recognised by the
WHO, the Joint Commission, AHRQ and the IHI as the standard handover structure, and
systematic reviews report that it improves the clarity and completeness of handover
communication. The ISBARQ variant adds an explicit questions section.

**The questions are not decoration.** A 2025 systematic review and meta-analysis of
randomised controlled trials found that question prompt lists significantly increased the
number of questions patients asked and their engagement in shared decision-making,
**without increasing consultation time**, and that lists accompanied by instructions
outperformed bare lists.

**Kept short on purpose.** Across studies of patient-generated health data in clinical
encounters the dominant barrier to clinicians using it is perceived relevance, ahead of
workflow and time.

Everything below is either measured by the device or said by the person, quoted with a
timestamp. Nothing here is generated by a language model, and nothing is inferred.
"""

import json
import sqlite3
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path

from wha.clock import now_utc
from wha.constants import (
    BASELINE_MIN_NIGHTS_PERSONAL,
    DETECT_CITATION,
    DETECT_RED_BPM,
    DETECT_YELLOW_BPM,
    SLEEP_WINDOW_CITATION,
)
from wha.db.connection import connect
from wha.db.migrations import apply_schema
from wha.safety.triage import load_triage_rules, rule_for


@dataclass
class Handover:
    """An SBAR summary with a question prompt list, ready to show or print."""

    subject_id: str
    generated_at_utc: datetime
    situation: list[str] = field(default_factory=list)
    background: list[str] = field(default_factory=list)
    assessment: list[str] = field(default_factory=list)
    recommendation: list[str] = field(default_factory=list)
    questions: list[str] = field(default_factory=list)
    what_this_is_not: list[str] = field(default_factory=list)

    def as_text(self) -> str:
        """Plain text, which is what actually gets copied into a message or printed."""
        blocks = [
            "SUMMARY FOR A CLINICIAN",
            (
                f"Generated {self.generated_at_utc.strftime('%Y-%m-%d %H:%M')} UTC by a "
                "consumer wearable monitoring app."
            ),
            "",
            "WHAT THIS IS NOT",
            *[f"  - {line}" for line in self.what_this_is_not],
            "",
            "SITUATION",
            *[f"  - {line}" for line in self.situation],
            "",
            "BACKGROUND",
            *[f"  - {line}" for line in self.background],
            "",
            "ASSESSMENT",
            *[f"  - {line}" for line in self.assessment],
            "",
            "RECOMMENDATION",
            *[f"  - {line}" for line in self.recommendation],
            "",
            "QUESTIONS YOU MIGHT ASK",
            "  Take this list in with you. Asking from a written list is shown to get more",
            "  of your questions answered without making the appointment longer.",
            *[f"  {n}. {q}" for n, q in enumerate(self.questions, start=1)],
        ]
        return "\n".join(blocks)


def _fmt_dt(raw: str | None) -> str:
    if not raw:
        return "unknown time"
    try:
        return datetime.fromisoformat(raw).strftime("%Y-%m-%d %H:%M")
    except ValueError:
        return raw


def build_handover(
    subject_id: str,
    episode_id: str | None = None,
    conn: sqlite3.Connection | None = None,
    db_path: Path | None = None,
) -> Handover:
    """Assemble the handover from what was measured and what was said."""
    close_conn = False
    if conn is None:
        conn = connect(db_path)
        apply_schema(conn)
        close_conn = True

    try:
        handover = Handover(subject_id=subject_id, generated_at_utc=now_utc())

        handover.what_this_is_not = [
            (
                "This is not a medical device and does not diagnose. It monitors resting "
                "heart rate during sleep from a consumer smartwatch."
            ),
            (
                "It measures heart rate and sleep only. It has no blood pressure, no "
                "temperature, no respiratory rate, no ECG and no blood tests."
            ),
            (
                "The specific watch model in use has not been independently validated for "
                f"nocturnal heart rate accuracy. Related validation: {SLEEP_WINDOW_CITATION}."
            ),
        ]

        # ---- Situation: why they are here, and anything urgent, first.
        urgent_turn = conn.execute(
            """SELECT text, urgency, triggered_flags_json, created_at_utc
                 FROM conversation_turns
                WHERE subject_id = ? AND urgency IS NOT NULL
                ORDER BY seq DESC LIMIT 1""",
            (subject_id,),
        ).fetchone()

        if urgent_turn is not None:
            flags = json.loads(urgent_turn["triggered_flags_json"] or "[]")
            handover.situation.append(
                f"The app advised seeking care at the '{urgent_turn['urgency']}' level on "
                f"{_fmt_dt(urgent_turn['created_at_utc'])}."
            )
            if flags:
                handover.situation.append(
                    "That was triggered by a fixed rule, not by an AI judgement. Rules "
                    f"matched: {', '.join(flags)}."
                )

        episode = None
        if episode_id:
            episode = conn.execute(
                "SELECT * FROM episodes WHERE episode_id = ?", (episode_id,)
            ).fetchone()
        if episode is None:
            episode = conn.execute(
                """SELECT * FROM episodes WHERE subject_id = ?
                   ORDER BY opened_on DESC LIMIT 1""",
                (subject_id,),
            ).fetchone()

        if episode is not None:
            handover.situation.append(
                f"An investigation opened on {episode['opened_on']} after the overnight "
                "resting heart rate rose above this person's own usual range."
            )
        elif not handover.situation:
            handover.situation.append(
                "No investigation is open. This summary was generated on request."
            )

        # ---- Background: what the device measured. Numbers, not impressions.
        #
        # The profile comes first, because it is the part a clinician can act on without
        # reading anything else, and because `notes_for_doctor` exists precisely so a
        # person can put something here that never enters a prompt. Information for the
        # doctor is not information for the model.
        from wha.service.settings import get_subject_profile

        profile = get_subject_profile(subject_id, conn=conn)
        described: list[str] = []
        if profile.age_years is not None:
            described.append(f"{profile.age_years} years old")
        if profile.sex:
            described.append(profile.sex)
        if profile.known_vascular_disease:
            described.append("known coronary, cerebrovascular or peripheral vascular disease")
        if described:
            handover.background.append("They recorded: " + ", ".join(described) + ".")
        if profile.rate_lowering_medicine:
            handover.background.append(
                "They take a medicine that lowers heart rate. This system is less able to "
                "detect an infection in them, because such medicines blunt the heart rate "
                "rise an infection causes."
            )
        if profile.notes_for_doctor:
            handover.background.append(
                f'They asked that you be told: "{profile.notes_for_doctor.strip()}". '
                "This text was never shown to the language model and played no part in "
                "anything the system concluded."
            )

        window_end = now_utc().date()
        if episode is not None:
            try:
                window_end = date.fromisoformat(episode["opened_on"]) + timedelta(days=7)
            except (TypeError, ValueError):
                pass
        window_start = window_end - timedelta(days=21)

        nights = conn.execute(
            """SELECT n.night_date, n.rhr_bpm, n.coverage_minutes, n.sleep_hours,
                      n.rhr_window_source, d.residual_bpm, d.level, d.flagged
                 FROM nightly_features n
                 LEFT JOIN detections d
                   ON d.subject_id = n.subject_id AND d.night_date = n.night_date
                WHERE n.subject_id = ? AND n.night_date BETWEEN ? AND ? AND n.usable = 1
                ORDER BY n.night_date DESC LIMIT 14""",
            (subject_id, window_start.isoformat(), window_end.isoformat()),
        ).fetchall()

        baseline = conn.execute(
            """SELECT centre_bpm, scale_bpm, usable_nights, rung FROM baselines
                WHERE subject_id = ? ORDER BY night_date DESC LIMIT 1""",
            (subject_id,),
        ).fetchone()

        if baseline is not None:
            handover.background.append(
                f"Their own baseline sleeping resting heart rate is "
                f"{baseline['centre_bpm']:.1f} bpm, established over "
                f"{baseline['usable_nights']} usable nights."
            )
            handover.background.append(
                "Nights are compared against that personal median, not against a "
                f"population average, once {BASELINE_MIN_NIGHTS_PERSONAL} nights exist. "
                f"A night is called elevated at {DETECT_YELLOW_BPM:.0f} bpm above it and "
                f"RED at {DETECT_RED_BPM:.0f} bpm above it, thresholds taken from "
                f"{DETECT_CITATION}."
            )

        if nights:
            handover.background.append("Readings, most recent first:")
            for night in nights:
                residual = night["residual_bpm"]
                above = (
                    f"{residual:+.1f} bpm vs baseline" if residual is not None else "no baseline"
                )
                source = night["rhr_window_source"] or "unknown window"
                sleep = (
                    f"{night['sleep_hours']:.1f} h sleep"
                    if night["sleep_hours"] is not None
                    else "sleep not recorded"
                )
                handover.background.append(
                    f"    {night['night_date']}: {night['rhr_bpm']:.0f} bpm, {above}, "
                    f"{sleep}, {night['coverage_minutes']} min coverage, "
                    f"measured over {source}"
                )
        else:
            handover.background.append("No usable nights were recorded in the last three weeks.")

        # ---- Assessment: what the person said, verbatim, and what any rule concluded.
        said = conn.execute(
            """SELECT text, created_at_utc FROM conversation_turns
                WHERE subject_id = ? AND role = 'user' ORDER BY seq ASC""",
            (subject_id,),
        ).fetchall()
        # Scoped to this person, and merged with the conversation into one timeline. The
        # two were listed as separate blocks each in its own order, so a clinician read
        # 20:10, then 20:11, then 18:29. That is not a history.
        answers = conn.execute(
            """SELECT i.question_text, i.answer_option_id, i.free_text, i.answered_at_utc
                 FROM interactions i
                 JOIN episodes e ON e.episode_id = i.episode_id
                WHERE e.subject_id = ? AND i.answer_option_id IS NOT NULL""",
            (subject_id,),
        ).fetchall()

        timeline: list[tuple[str, str]] = [
            (str(row["created_at_utc"]), f'"{row["text"]}"') for row in said
        ]
        for row in answers:
            free = f' and added "{row["free_text"]}"' if row["free_text"] else ""
            timeline.append(
                (
                    str(row["answered_at_utc"]),
                    f'asked "{row["question_text"]}", answered "{row["answer_option_id"]}"{free}',
                )
            )

        if timeline:
            handover.assessment.append("What they reported, in their own words:")
            for stamp, entry in sorted(timeline):
                handover.assessment.append(f"    {_fmt_dt(stamp)}: {entry}")
        else:
            handover.assessment.append("They have not reported any symptoms to the app.")

        # Any validated decision rule that was run, with its score and its source.
        triage_rows = conn.execute(
            """SELECT presentation, item_id, answer, source_text FROM triage_answers
                WHERE subject_id = ?""",
            (subject_id,),
        ).fetchall()
        if triage_rows:
            presentation = triage_rows[0]["presentation"]
            rule = rule_for(presentation)
            if rule is not None:
                items = {i.id: i for i in rule.items}
                handover.assessment.append(
                    f"The app ran the {rule.label}, a decision rule for this presentation "
                    f"that uses history alone. Source: {rule.citation}"
                )
                total = 0
                for row in triage_rows:
                    item = items.get(row["item_id"])
                    if item is None:
                        continue
                    given = bool(row["answer"])
                    # What is printed is the question that was asked and the answer that
                    # was given, not the condition that scores. Printing the scored label
                    # against the raw answer inverts an inverted item: the person said
                    # pressing DOES reproduce the pain, and the line read "pain not
                    # reproducible: yes", which tells a clinician the opposite of the
                    # truth on a document written for them.
                    counts = (not given) if item.inverted else given
                    total += item.points if counts else 0
                    quote = f' ("{row["source_text"]}")' if row["source_text"] else ""
                    handover.assessment.append(
                        f"    {item.question_intent.strip()} "
                        f"-> {'yes' if given else 'no'}{quote} "
                        f"[scores {item.points if counts else 0}]"
                    )
                handover.assessment.append(
                    f"    Total {total} of {sum(i.points for i in rule.items)}. "
                    f"The published cut-off is {int(rule.performance.get('cutoff', 0))}."
                )
                handover.assessment.append(
                    f"    Rule limitation as published: {rule.contraindication}"
                )

        outcome_row = conn.execute(
            """SELECT o.payload_json FROM outcomes o
                 JOIN episodes e ON e.episode_id = o.episode_id
                WHERE e.subject_id = ? ORDER BY o.created_at_utc DESC LIMIT 1""",
            (subject_id,),
        ).fetchone()
        if outcome_row is not None:
            outcome = json.loads(outcome_row["payload_json"])
            handover.assessment.append(
                f"The app's own conclusion was '{outcome.get('disposition')}'. "
                "This is a monitoring disposition, not a diagnosis."
            )
            differential = outcome.get("differential") or []
            if differential:
                handover.assessment.append(
                    "Causes the app weighed, with its own internal weights. THESE ARE NOT "
                    "CLINICAL PROBABILITIES and were computed only from heart rate, sleep "
                    "and the answers above:"
                )
                for item in differential[:5]:
                    handover.assessment.append(f"    {item['cause']}: {item['probability']}")

        # ---- Recommendation: what it advised, and what it cannot see.
        if urgent_turn is not None:
            handover.recommendation.append(
                f"The app advised care at the '{urgent_turn['urgency']}' level. It cannot "
                "assess whether that was right, which is why this summary exists."
            )
        handover.recommendation.append(
            "What this app cannot assess: blood pressure, temperature, oxygen delivery, "
            "any blood result, any ECG, and anything requiring examination."
        )
        config = load_triage_rules()
        if config.no_validated_rule:
            handover.recommendation.append(
                "For these presentations the app has no decision rule that works from "
                "history alone, so it escalates rather than assessing: "
                f"{', '.join(config.no_validated_rule)}. Expect over-escalation there."
            )

        # ---- Questions. Process questions about this data, never clinical assertions.
        handover.questions = [
            (
                "Does this pattern of overnight heart rate change anything for you, or is "
                "it not clinically useful here?"
            ),
            (
                "Is there anything about how I sleep or what I take that would raise my "
                "overnight heart rate on its own?"
            ),
            (
                "Should I keep recording this, and is there a number at which I should "
                "contact you rather than wait?"
            ),
            "What would you want me to look out for between now and any follow-up?",
        ]
        if triage_rows:
            handover.questions.insert(
                0,
                "The app ran a published chest pain rule on my answers. Would you like to "
                "see the answers I gave it?",
            )

        return handover
    finally:
        if close_conn:
            conn.close()
