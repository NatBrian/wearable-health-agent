"""Render evaluation results as a markdown report.

Evaluation used to be a dashboard page. It was rewritten six times and remained hard to
read, which is the expected outcome: the dashboard's reader is a person checking their
own health, and benchmark accuracy against comparator policies is not something they act
on. It is evidence about whether the system works, aimed at someone assessing it.

That reader is better served by a file in the repository. It renders on GitHub, it diffs
when the numbers move, it can be read without starting a server, and it has room for the
caveats that matter more than the figures.
"""

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from wha.models import EvaluationResult

_POLICY_LABELS = {
    "evsi": "EVSI (this system)",
    "threshold": "Fixed threshold",
    "never_ask": "Never ask",
    "always_ask": "Always ask",
    "random": "Random",
}

_POLICY_NOTES = {
    "evsi": "Asks only when an answer could change the decision.",
    "threshold": "Asks whenever illness probability clears a fixed cut-off.",
    "never_ask": "Decides on sensor data alone. The comparator that matters most.",
    "always_ask": "Asks every available question. An upper bound on accuracy, at a cost.",
    "random": "Asks at random. A floor that any real policy must beat.",
}


def _format_policy_table(metrics: dict[str, float]) -> list[str]:
    """Accuracy and interruption cost for each policy, best accuracy last."""
    rows = []
    for key, label in _POLICY_LABELS.items():
        accuracy = metrics.get(f"{key}_mean_accuracy")
        interruptions = metrics.get(f"{key}_mean_interruptions")
        if accuracy is None:
            continue
        rows.append((label, accuracy, interruptions or 0.0, _POLICY_NOTES.get(key, "")))

    lines = [
        "| Policy | Accuracy | Questions per episode | What it does |",
        "|---|---|---|---|",
    ]
    for label, accuracy, interruptions, note in rows:
        lines.append(f"| {label} | {accuracy:.3f} | {interruptions:.2f} | {note} |")
    return lines


def _format_frontier(rows: list[dict[str, Any]]) -> list[str]:
    """How the interruption cost weight trades accuracy against questions asked."""
    lines = [
        "| Interruption cost weight | Accuracy | Questions per episode |",
        "|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['interruption_cost_weight']:.2f} "
            f"| {row['evsi_accuracy']:.3f} "
            f"| {row['evsi_interruptions']:.2f} |"
        )
    return lines


def render_markdown(results: dict[str, EvaluationResult]) -> str:
    """Build the full report from whichever suites have results."""
    generated = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

    lines: list[str] = [
        "# Evaluation",
        "",
        "Generated by `uv run wha eval-report`. Every number here is produced by running",
        "the system; none is written by hand.",
        "",
        f"_Last run: {generated}_",
        "",
    ]

    policy = results.get("policy")
    if policy is not None:
        lines += [
            "## Does asking actually help?",
            "",
            "The system's central claim is that a wrist sensor cannot tell infection from",
            "the things that mimic it, and that asking one well-chosen question can. This",
            "measures that claim against four alternative strategies on the same cases.",
            "",
            f"Cases: **{policy.sample_size}**, split evenly between real infections and benign",
            "mimics producing an identical heart rate elevation. The even split is deliberate:",
            'with infections only, a policy that always answered "illness" would score 100%.',
            "",
        ]
        lines += _format_policy_table(policy.metrics)
        lines += [
            "",
            "**Never ask scores at chance.** That is the finding the rest of the system rests",
            "on: the sensor data alone carries no usable signal about which cause is present.",
            "Asking is what separates them.",
            "",
        ]

        frontier = policy.tables.get("accuracy_interruption_frontier")
        if frontier:
            lines += [
                "### What it costs to ask more",
                "",
                "`POLICY_COST_PER_INTERRUPT` sets how reluctant the system is to interrupt.",
                "Lower values buy accuracy by asking more often.",
                "",
            ]
            lines += _format_frontier(frontier)
            lines += [""]

        if policy.caveats:
            lines += ["### What these numbers do not show", ""]
            lines += [f"- {c}" for c in policy.caveats]
            lines += [""]

    detection = results.get("detection")
    if detection is not None:
        lines += ["## Detection", ""]
        if detection.metrics:
            lines += ["| Metric | Value |", "|---|---|"]
            for key, value in sorted(detection.metrics.items()):
                lines.append(f"| {key} | {value} |")
        else:
            lines.append("No detection metrics were produced.")
        lines += [""]
        if detection.caveats:
            lines += [f"- {c}" for c in detection.caveats] + [""]
    else:
        lines += _detection_from_cohort()

    lines += [
        "## Scenarios",
        "",
        "Eleven frozen scenarios in `tests/fixtures/scenarios/` each state the disposition,",
        "escalation and question count they expect. `uv run wha demo run <name>` runs one end",
        "to end and exits non-zero if the run does not meet them.",
        "",
    ]

    return "\n".join(lines).rstrip() + "\n"


DETECTION_RESULTS = Path("docs/detection-results.json")


def _detection_from_cohort() -> list[str]:
    """The detection section, from the summary `tools/cohort/report.py` writes.

    This said "Not evaluated. Detection accuracy needs the Stanford and PMData cohorts and
    their ground-truth labels", and it said so for the life of the project. The data was
    never missing: it is a public 378 MB download and the symptom dates are in the same
    paper's supplementary spreadsheet, shifted the same way as the wearable files.

    Read from a committed summary rather than recomputed here, so there is exactly one
    implementation of the scoring and the 378 MB cohort does not have to be present to
    render the report.
    """
    if not DETECTION_RESULTS.exists():
        return [
            "## Detection",
            "",
            "**Not measured in this checkout.** Produce it with:",
            "",
            "```bash",
            "uv run python tools/cohort/fetch.py",
            "uv run python tools/cohort/labels.py",
            "uv run python tools/cohort/evaluate.py",
            "uv run python tools/cohort/report.py",
            "```",
            "",
        ]

    data = json.loads(DETECTION_RESULTS.read_text(encoding="utf-8"))
    burden = data.get("alert_burden", {})
    ours = burden.get("wha_clock", {})
    theirs = burden.get("nightsignal", {})

    lines = [
        "## Detection",
        "",
        f"Measured on **{data['participants']} people and {data['nights']:,} nights** of the",
        "public Mishra et al. 2020 wearable release, with symptom onset dates from the same",
        (
            f"paper's supplementary data. **{data['covid_cases_with_onset']} labelled "
            f"COVID-19 cases** and **{data['unlabelled']} people with no illness label**."
        ),
        "",
        "**Always read the chance column.** A wide window makes any detector look good, so",
        "the third column is a detector that alerts on the same NUMBER of runs as this one,",
        "placed at random, averaged over 2,000 draws. 80 percent against a 66 percent floor",
        "is not a finding. 47 against 17 is.",
        "",
        "| Alert fired within | This system | Published NightSignal | Random, same rate |",
        "|---|---|---|---|",
    ]
    for window in data.get("windows", []):
        label = f"{window['days_before']} days before onset, {window['days_after']} after"
        lines.append(
            f"| {label} | **{window['this_system']:.1%}** | {window['nightsignal']:.1%} "
            f"| {window['random_rate_matched']:.1%} |"
        )

    lines += [
        "",
        "**It matches the published algorithm rather than beating it, and that is the",
        "honest reading.** An earlier version of this system flagged on two raised nights",
        "with at least one red, which is looser than NightSignal's two consecutive red",
        "nights, and scored about 6 points higher at every window for 37 percent more",
        "investigations. That rule was quietly not the one being cited. It was changed to",
        "the published rule on 5 September 2026, and the two now agree case for case.",
        "",
        "What survives is the lead time and the quiet. At the seven day window this system",
        "warns a median of **3.0 days** before symptoms against NightSignal's 1.5, and it",
        "opens fewer investigations on people who were never ill:",
        "",
        "| On 76 people with no illness label | This system | Published NightSignal |",
        "|---|---|---|",
        (
            f"| Investigations over {ours.get('person_weeks', 0):.0f} person-weeks "
            f"| {ours.get('investigations', 0)} | {theirs.get('investigations', 0)} |"
        ),
        (
            f"| Per person-week | **{ours.get('per_person_week', 0):.3f}** "
            f"| {theirs.get('per_person_week', 0):.3f} |"
        ),
        (
            f"| One investigation every | **{ours.get('one_every_weeks', 0):.1f} weeks** "
            f"| {theirs.get('one_every_weeks', 0):.1f} weeks |"
        ),
        (
            f"| Never alerted at all | {ours.get('never_alerted', 0)} of 76 "
            f"| {theirs.get('never_alerted', 0)} of 76 |"
        ),
        "",
        "### What these numbers do not show",
        "",
        f"- **{data['usable_nights']:,} of {data['nights']:,} nights** cleared the coverage",
        "  floor. The rest were not scored at all rather than guessed at.",
        "- One cohort, one device, one illness. These are Fitbit users in a COVID-19 study,",
        "  not a general population, and the only labelled illness is COVID-19.",
        "- Scored on the clock window, because only 32 of the 120 participants have sleep",
        "  staging. The window this build actually uses is measured separately in",
        "  `docs/DESIGN-SLEEP-WINDOW.md`, where it turns out to be strongly justified for an",
        "  unconventional sleeper and roughly neutral otherwise.",
        "- Sensitivity here is per PERSON, not per night, and an alert anywhere in the",
        "  window counts. That is the right question for an early-warning system and it is a",
        "  looser one than per-night accuracy.",
        "",
        f"Reproduce all of it: `{data['source']}`",
        "",
        "Every deviation from the algorithm these thresholds come from is listed, with the",
        "evidence for each, in `docs/DESIGN-VS-NIGHTSIGNAL.md`.",
        "",
    ]
    return lines


def write_report(
    output_path: Path | None = None,
    eval_dir: Path | None = None,
) -> Path:
    """Run the suites that can run offline and write the markdown report."""
    from wha.eval.policy_oracle import run_policy_eval

    target = output_path if output_path is not None else Path("EVALUATION.md")
    results: dict[str, EvaluationResult] = {"policy": run_policy_eval(eval_dir=eval_dir)}

    target.write_text(render_markdown(results), encoding="utf-8")
    return target
